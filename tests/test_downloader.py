"""Downloader tests (M1.8 + M1.9) — httpx.MockTransport only, no network.

Covers success + hash correctness against a Pillow-generated fixture, 404,
5xx retry, retry exhaustion, size limits (header and mid-stream), content-type
rejection/mismatch, GIF + MP4/WebM video support, redirect following, atomic
writes (no partial files), filename sanitization/path traversal, and the
Level-1 URL duplicate skip callback (PRD §11, §12, §41, §52).
"""

from __future__ import annotations

import asyncio
import hashlib
from collections.abc import AsyncIterator, Callable
from pathlib import Path

import httpx

from backend.scraper.adapters import CommentMeta, MediaRef
from backend.scraper.downloader import (
    DownloadStatus,
    Downloader,
    sanitize_filename,
)

CDN = "https://cdn.example.com/media"

#: Minimal MP4 (ftyp box at offset 4) and WebM (EBML magic) container headers.
MP4_BYTES = b"\x00\x00\x00\x18ftypisom\x00\x00\x00\x00isomiso2avc1mp41" + b"\x00" * 64
WEBM_BYTES = b"\x1a\x45\xdf\xa3\x01\x00\x00\x00\x00\x00\x00\x1f" + b"\x00" * 64

Handler = Callable[[httpx.Request], httpx.Response]


def media_ref(url: str, *, original_filename: str | None = None) -> MediaRef:
    return MediaRef(
        url=url,
        kind="image",
        comment=CommentMeta(comment_id="42", author_name="tester"),
        original_filename=original_filename,
    )


def make_client(handler: Handler) -> httpx.AsyncClient:
    return httpx.AsyncClient(transport=httpx.MockTransport(handler), follow_redirects=True)


def make_downloader(
    destination: Path, client: httpx.AsyncClient, make_settings, **crawler_overrides
) -> Downloader:
    return Downloader(
        destination_dir=destination,
        settings=make_settings(**crawler_overrides),
        client=client,
    )


def png_bytes(sample_images: dict[str, Path]) -> bytes:
    return sample_images["png"].read_bytes()


async def test_success_writes_file_and_correct_sha256(
    tmp_path: Path, make_settings, sample_images: dict[str, Path]
) -> None:
    """Hash matches hashlib over Pillow-generated bytes; no temp files remain (PRD §11)."""
    body = png_bytes(sample_images)
    destination = tmp_path / "media"

    def handler(request: httpx.Request) -> httpx.Response:
        return httpx.Response(200, content=body, headers={"content-type": "image/png"})

    client = make_client(handler)
    downloader = make_downloader(destination, client, make_settings)
    try:
        result = await downloader.download(media_ref(f"{CDN}/meme.png"))
    finally:
        await client.aclose()

    assert result.ok
    assert result.status is DownloadStatus.OK
    assert result.path == destination / "meme.png"
    assert result.path.is_file()
    assert result.path.read_bytes() == body
    assert result.sha256 == hashlib.sha256(body).hexdigest()
    assert result.size == len(body)
    assert result.content_type == "image/png"
    assert result.kind == "image"
    assert [entry.name for entry in destination.iterdir()] == ["meme.png"]


