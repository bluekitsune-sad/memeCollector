async def test_path_traversal_in_target_name_neutralized(
    tmp_path: Path, make_settings, sample_images: dict[str, Path]
) -> None:
    body = png_bytes(sample_images)

    def handler(request: httpx.Request) -> httpx.Response:
        return httpx.Response(200, content=body, headers={"content-type": "image/png"})

    destination = tmp_path / "media"
    client = make_client(handler)
    downloader = make_downloader(destination, client, make_settings)
    try:
        result = await downloader.download(
            media_ref(f"{CDN}/evil.png"), target_name="../../evil.png"
        )
        backslash = await downloader.download(
            media_ref(f"{CDN}/evil2.png"), target_name="..\\..\\evil2.png"
        )
    finally:
        await client.aclose()

    assert result.ok and result.path == destination / "evil.png"
    assert backslash.ok and backslash.path == destination / "evil2.png"
    assert (destination / "evil.png").is_file()
    assert not (destination.parent.parent / "evil.png").exists()


async def test_original_filename_and_url_basename_used(
    tmp_path: Path, make_settings, sample_images: dict[str, Path]
) -> None:
    body = png_bytes(sample_images)

    def handler(request: httpx.Request) -> httpx.Response:
        return httpx.Response(200, content=body, headers={"content-type": "image/png"})

    destination = tmp_path / "media"
    client = make_client(handler)
    downloader = make_downloader(destination, client, make_settings)
    try:
        named = await downloader.download(
            media_ref(f"{CDN}/whatever.png", original_filename="My Meme.png")
        )
        from_url = await downloader.download(media_ref(f"{CDN}/dir/funny-meme.gif?sig=abc"))
        no_ext = await downloader.download(media_ref(f"{CDN}/bare"))
    finally:
        await client.aclose()

    assert named.path == destination / "My Meme.png"
    # URL basename wins only without original_filename; a missing extension is
    # appended from the sniffed content type (a provided one is kept as-is).
    assert from_url.path == destination / "funny-meme.gif"
    assert no_ext.path == destination / "bare.png"


def test_sanitize_filename_blocks_traversal_and_reserved_names() -> None:
    assert sanitize_filename("../../etc/passwd") == "passwd"
    assert sanitize_filename("..\\..\\windows\\system32\\evil.png") == "evil.png"
    assert sanitize_filename("..%2f..%2fevil.png") == "evil.png"
    assert sanitize_filename('a<b>|c?.png') == "a_b__c_.png"
    assert sanitize_filename("CON.png") == "_CON.png"
    assert sanitize_filename("nul.txt") == "_nul.txt"
    assert sanitize_filename("  ..  ") == "download"
    assert sanitize_filename("") == "download"
    assert sanitize_filename(".hidden.png") == "hidden.png"
    long_name = "x" * 300 + ".png"
    assert len(sanitize_filename(long_name)) <= 116


def test_aclose_keeps_injected_client_open(make_settings) -> None:
    client = make_client(lambda request: httpx.Response(200))
    downloader = Downloader(destination_dir=Path("."), settings=make_settings(), client=client)

    async def close_and_probe() -> None:
        await downloader.aclose()
        response = await client.get("https://fixture.test/still-open")
        assert response.status_code == 200
        await client.aclose()

    asyncio.run(close_and_probe())
