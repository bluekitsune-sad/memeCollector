async def test_500_then_success_retries_with_backoff(tmp_path: Path, make_settings) -> None:
    calls: list[int] = []

    def handler(request: httpx.Request) -> httpx.Response:
        calls.append(1)
        if len(calls) == 1:
            return httpx.Response(500)
        return httpx.Response(200, content=MP4_BYTES, headers={"content-type": "video/mp4"})

    destination = tmp_path / "media"
    client = make_client(handler)
    downloader = make_downloader(destination, client, make_settings, retry_attempts=3)
    try:
        result = await downloader.download(media_ref(f"{CDN}/clip.mp4"))
    finally:
        await client.aclose()

    assert result.ok
    assert result.kind == "video"
    assert len(calls) == 2


